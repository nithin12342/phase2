"""H5 Dataset loader for pre-processed OmniFusion features.

Loads embeddings and labels directly from H5 files generated by the
H5_OmniFusion_Colab_Runner pipeline.
"""

import torch
from torch.utils.data import Dataset, DataLoader
import numpy as np
import h5py
from pathlib import Path
from typing import Dict, List, Optional, Tuple
import os

try:
    from sklearn.model_selection import StratifiedKFold, train_test_split
except ImportError:
    StratifiedKFold = None
    train_test_split = None


class H5OmniFusionDataset(Dataset):
    """
    Dataset for pre-extracted H5-OmniFusion features.
    
    Each H5 file contains:
    - {PID}/audio_embedding: (768,)
    - {PID}/text_embedding: (768,)
    - {PID}/video_embedding: (768,)
    - {PID}/face_embedding: (768,)
    - {PID}/tabular_embedding: (768,)
    - {PID}/fusion_embedding: (768,)
    - {PID}/phq8_score: (1,) or scalar
    """
    
    EMBEDDING_KEYS = [
        'audio_embedding',
        'text_embedding', 
        'video_embedding',
        'face_embedding',
        'tabular_embedding',
    ]
    
    def __init__(
        self,
        h5_dir: str,
        participant_ids: Optional[List[int]] = None,
        labels_csv: Optional[str] = None,
        depression_threshold: int = 10,
        max_seq_len: int = 512,
    ):
        """
        Initialize dataset.
        
        Args:
            h5_dir: Directory containing .h5 files (one per participant)
            participant_ids: Optional list of PIDs to use (for train/val/test splits)
            labels_csv: Optional CSV with PHQ8 labels (overrides H5-embedded labels)
            depression_threshold: PHQ8 score >= this is considered depressed
            max_seq_len: Maximum sequence length for temporal features
        """
        self.h5_dir = Path(h5_dir)
        self.depression_threshold = depression_threshold
        self.labels_csv = labels_csv
        self.max_seq_len = max_seq_len
        
        self._h5_paths = {}  # Will be populated by _discover_participants
        if participant_ids is not None:
            self._discover_participants()
            self.participant_ids = [p for p in participant_ids if p in self._h5_paths]
        else:
            self.participant_ids = self._discover_participants()
        
        self.external_labels = None
        if labels_csv and os.path.exists(labels_csv):
            self._load_external_labels(labels_csv)
        
        print(f"[H5Dataset] Loaded {len(self.participant_ids)} participants from {h5_dir}")
        
        self._print_label_distribution()
    
    def _discover_participants(self) -> List[str]:
        """Discover available participant IDs from H5 files (recursive search)."""
        pids = []
        self._h5_paths = {}  # Store {pid: path} mapping
        
        for root, dirs, files in os.walk(str(self.h5_dir)):
            for file in files:
                if file.lower().endswith(".h5"):
                    h5_file = Path(root) / file
                    pid = h5_file.stem
                    pids.append(pid)
                    self._h5_paths[pid] = h5_file
        
        if len(pids) == 0:
            print(f"[Warning] No H5 files found in {self.h5_dir}")
        else:
            print(f"[H5Dataset] Found {len(pids)} H5 files across subdirectories of {self.h5_dir}")
            subdirs = set(Path(p).parent.name for p in self._h5_paths.values())
            print(f"[H5Dataset] Discovered subdirectories: {', '.join(subdirs)}")
            
        return sorted(pids)
    
    def _get_h5_path(self, pid: str) -> Optional[Path]:
        """Get the H5 file path for a participant ID."""
        if hasattr(self, '_h5_paths') and str(pid) in self._h5_paths:
            return self._h5_paths[str(pid)]
        fallback_path = self.h5_dir / f"{pid}.h5"
        if fallback_path.exists():
            return fallback_path
        return None
    
    def _load_external_labels(self, csv_path: str):
        """Load labels from external CSV file."""
        import pandas as pd
        df = pd.read_csv(csv_path)
        
        id_col = None
        for col in ['Participant_ID', 'participant_id', 'ID', 'id', 'PID']:
            if col in df.columns:
                id_col = col
                break
        
        phq_col = None
        for col in ['PHQ8_Score', 'phq8_score', 'PHQ_Score', 'phq_score']:
            if col in df.columns:
                phq_col = col
                break
        
        if id_col and phq_col:
            self.external_labels = {str(k): v for k, v in zip(df[id_col], df[phq_col])}
            print(f"[H5Dataset] Loaded {len(self.external_labels)} external labels from {csv_path}")
    
    def _print_label_distribution(self):
        """Print the distribution of depression labels."""
        if len(self.participant_ids) > 200 and self.external_labels is None:
            print(f"[H5Dataset] Skipping distribution check for {len(self.participant_ids)} participants (too slow without CSV)")
            return

        pos_count = 0
        neg_count = 0
        
        for pid in self.participant_ids:
            if self.external_labels and pid in self.external_labels:
                phq = float(self.external_labels[pid])
                if phq >= self.depression_threshold:
                    pos_count += 1
                else:
                    neg_count += 1
            elif len(self.participant_ids) <= 200:
                labels = self._get_labels(pid)
                if labels['binary'].item() == 1:
                    pos_count += 1
                else:
                    neg_count += 1
        
        total = pos_count + neg_count
        if total > 0:
            print(f"[H5Dataset] Label distribution: {pos_count} depressed ({100*pos_count/total:.1f}%), "
                  f"{neg_count} non-depressed ({100*neg_count/total:.1f}%)")
        else:
            print(f"[H5Dataset] Label distribution: No labels found")
    
    def __len__(self) -> int:
        return len(self.participant_ids)
    
    def set_training(self, is_training: bool = True):
        """Set training mode for data augmentation."""
        self.is_training = is_training
    
    def __getitem__(self, idx: int) -> Dict[str, torch.Tensor]:
        """Get a single sample with optional augmentation."""
        pid = self.participant_ids[idx]
        h5_path = self._get_h5_path(pid)
        
        sample = {}
        
        with h5py.File(h5_path, 'r') as f:
            if str(pid) in f:
                grp = f[str(pid)]
            else:
                grp = f  # Features at root level
            
            for key in self.EMBEDDING_KEYS:
                h5_key = None
                if key in grp:
                    h5_key = key
                elif key.replace('_embedding', '_features') in grp:
                    h5_key = key.replace('_embedding', '_features')
                
                if h5_key:
                    data = grp[h5_key][()]
                    tensor = torch.from_numpy(data).float()
                    
                    if torch.isnan(tensor).any() or torch.isinf(tensor).any():
                        tensor = torch.nan_to_num(tensor, nan=0.0, posinf=0.0, neginf=0.0)
                    
                    if tensor.shape[-1] != 768:
                        target_dim = 768
                        current_dim = tensor.shape[-1]
                        padding = torch.zeros((*tensor.shape[:-1], target_dim - current_dim))
                        tensor = torch.cat([tensor, padding], dim=-1)
                    
                    if tensor.dim() > 1 and tensor.shape[0] > self.max_seq_len:
                        tensor = tensor[:self.max_seq_len, :]
                    
                    sample[key.replace('_embedding', '_features')] = tensor
                else:
                    sample[key.replace('_embedding', '_features')] = torch.zeros(768)
            
            for k, v in sample.items():
                if isinstance(v, torch.Tensor) and (torch.isnan(v).any() or torch.isinf(v).any()):
                   print(f"CRITICAL ERROR: PID {pid} still has NaN/Inf in {k} after loading")
                   sample[k] = torch.nan_to_num(v, nan=0.0)
            
            if 'quality_scores' in grp:
                qs = grp['quality_scores'][()]
                qs_tensor = torch.nan_to_num(torch.from_numpy(qs).float(), nan=0.5, posinf=1.0, neginf=0.0)
                
                sample['quality_inputs'] = {
                    'audio_quality': qs_tensor[0],
                    'text_length': qs_tensor[1] * 500.0, 
                    'video_motion': qs_tensor[2],
                    'face_confidence': qs_tensor[3],
                    'tabular_completeness': qs_tensor[4],
                }
            else:
                sample['quality_inputs'] = {
                    'audio_quality': torch.tensor(0.5, dtype=torch.float),
                    'text_length': torch.tensor(100.0, dtype=torch.float),
                    'video_motion': torch.tensor(0.5, dtype=torch.float),
                    'face_confidence': torch.tensor(0.5, dtype=torch.float),
                    'tabular_completeness': torch.tensor(1.0, dtype=torch.float),
                }

        
        if getattr(self, 'is_training', False):
            sample = self._augment(sample)
        
        sample['targets'] = self._get_labels(pid)
        sample['participant_id'] = pid
        
        return sample
    
    def _augment(self, sample: Dict[str, torch.Tensor]) -> Dict[str, torch.Tensor]:
        """Apply data augmentation to features."""
        for key in ['audio_features', 'text_features', 'video_features', 'face_features', 'tabular_features']:
            if key in sample:
                features = sample[key]
                
                feature_std = features.std().item() if features.numel() > 1 else 0.0
                noise_std = 0.01 * feature_std + 1e-6
                noise = torch.randn_like(features) * noise_std
                features = features + noise
                
                if torch.rand(1).item() < 0.5:  # 50% chance to apply
                    mask = torch.rand_like(features) > 0.1
                    features = features * mask
                
                sample[key] = features
        
        return sample

    
    def _get_labels(self, pid: str) -> Dict[str, torch.Tensor]:
        """Get labels for a participant."""
        phq_score = 0.0
        
        if self.external_labels and pid in self.external_labels:
            phq_score = float(self.external_labels[pid])
        else:
            h5_path = self._get_h5_path(pid)
            if h5_path and h5_path.exists():
                with h5py.File(h5_path, 'r') as f:
                    if str(pid) in f:
                        grp = f[str(pid)]
                    else:
                        grp = f
                    
                    if 'phq8_score' in grp:
                        score = grp['phq8_score'][()]
                        phq_score = float(score.item() if hasattr(score, 'item') else score)
        
        binary = 1 if phq_score >= self.depression_threshold else 0
        
        return {
            'binary': torch.tensor(binary, dtype=torch.long),
            'phq_score': torch.tensor(phq_score, dtype=torch.float),
        }


def h5_collate_fn(batch: List[Dict]) -> Dict[str, torch.Tensor]:
    """Custom collate function for H5 batches."""
    result = {}
    
    for key in batch[0].keys():
        if key == 'targets':
            result['targets'] = {
                'binary': torch.stack([b['targets']['binary'] for b in batch]),
                'phq_score': torch.stack([b['targets']['phq_score'] for b in batch]),
            }
        elif key == 'quality_inputs':
            result['quality_inputs'] = {}
            for qk in batch[0]['quality_inputs'].keys():
                result['quality_inputs'][qk] = torch.stack([b['quality_inputs'][qk] for b in batch])
        elif key == 'participant_id':
            result['participant_id'] = [b['participant_id'] for b in batch]
        elif torch.is_tensor(batch[0][key]):
            standardized = []
            for b in batch:
                t = b[key]
                if t.dim() == 1:
                    t = t.unsqueeze(0) # [D] -> [1, D]
                standardized.append(t)
            
            shapes = [t.shape for t in standardized]
            if len(set(shapes)) > 1:
                max_t = max(s[0] for s in shapes)
                padded = []
                for t in standardized:
                    if t.shape[0] < max_t:
                        pad_size = (0, 0, 0, max_t - t.shape[0]) # (left, right, top, bottom) for 2D
                        t = torch.nn.functional.pad(t, (0, 0, 0, max_t - t.shape[0]))
                    padded.append(t)
                result[key] = torch.stack(padded)
            else:
                result[key] = torch.stack(standardized)
    
    return result


def create_h5_dataloaders(
    h5_dir: str,
    batch_size: int = 8,
    num_workers: int = 0,
    train_ratio: float = 0.7,
    val_ratio: float = 0.15,
    test_ratio: float = 0.15,
    seed: int = 42,
    labels_csv: Optional[str] = None,
    max_seq_len: int = 512,
) -> Tuple[DataLoader, DataLoader, DataLoader]:
    """
    Create train/val/test dataloaders from H5 files.
    
    Args:
        h5_dir: Directory containing .h5 files
        batch_size: Batch size for dataloaders
        num_workers: Number of workers (0 for Colab compatibility)
        train_ratio: Fraction for training (default 0.7)
        val_ratio: Fraction for validation (default 0.15)
        test_ratio: Fraction for test (default 0.15)
        seed: Random seed for reproducibility
        labels_csv: Optional path to labels CSV
        
    Returns:
        Tuple of (train_loader, val_loader, test_loader)
    """
    full_dataset = H5OmniFusionDataset(h5_dir, labels_csv=labels_csv, max_seq_len=max_seq_len)
    all_pids = full_dataset.participant_ids
    
    labels = []
    for pid in all_pids:
        lbl = full_dataset._get_labels(pid)
        labels.append(lbl['binary'].item())
    
    np.random.seed(seed)
    
    if train_test_split is not None:
        train_pids, temp_pids, train_labels, temp_labels = train_test_split(
            all_pids, labels, 
            train_size=train_ratio, 
            stratify=labels, 
            random_state=seed
        )
        
        val_size = val_ratio / (val_ratio + test_ratio)
        val_pids, test_pids, _, _ = train_test_split(
            temp_pids, temp_labels,
            train_size=val_size,
            stratify=temp_labels,
            random_state=seed
        )
    else:
        n = len(all_pids)
        indices = np.random.permutation(n)
        train_end = int(n * train_ratio)
        val_end = int(n * (train_ratio + val_ratio))
        
        train_pids = [all_pids[i] for i in indices[:train_end]]
        val_pids = [all_pids[i] for i in indices[train_end:val_end]]
        test_pids = [all_pids[i] for i in indices[val_end:]]
    
    print(f"\n[H5Dataset] Split: Train={len(train_pids)}, Val={len(val_pids)}, Test={len(test_pids)}")
    
    train_dataset = H5OmniFusionDataset(h5_dir, participant_ids=train_pids, labels_csv=labels_csv, max_seq_len=max_seq_len)
    val_dataset = H5OmniFusionDataset(h5_dir, participant_ids=val_pids, labels_csv=labels_csv, max_seq_len=max_seq_len)
    test_dataset = H5OmniFusionDataset(h5_dir, participant_ids=test_pids, labels_csv=labels_csv, max_seq_len=max_seq_len)
    
    train_loader = DataLoader(
        train_dataset,
        batch_size=batch_size,
        shuffle=True,
        num_workers=num_workers,
        collate_fn=h5_collate_fn,
        pin_memory=True,
    )
    
    val_loader = DataLoader(
        val_dataset,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        collate_fn=h5_collate_fn,
        pin_memory=True,
    )
    
    test_loader = DataLoader(
        test_dataset,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        collate_fn=h5_collate_fn,
        pin_memory=True,
    )
    
    return train_loader, val_loader, test_loader


def create_h5_dataloaders_kfold(
    h5_dir: str,
    labels_csv: str,
    batch_size: int = 8,
    num_workers: int = 0,
    n_folds: int = 5,
    fold_idx: int = 0,
    seed: int = 42,
    max_seq_len: int = 512,
) -> Tuple[DataLoader, DataLoader, DataLoader]:
    """
    Create train/val/test dataloaders with K-Fold CV support.
    
    Uses merged labels CSV for all datasets (DAIC-WOZ, Extended-DAIC, EATD-Corpus).
    
    Args:
        h5_dir: Directory containing .h5 files (searches recursively)
        labels_csv: Path to merged_labels.csv with columns: Participant_ID, PHQ8_Score
        batch_size: Batch size for dataloaders
        num_workers: Number of workers (0 for Colab compatibility)
        n_folds: Number of CV folds
        fold_idx: Current fold index (0 to n_folds-1)
        seed: Random seed for reproducibility
        max_seq_len: Maximum sequence length for temporal features
        
    Returns:
        Tuple of (train_loader, val_loader, test_loader)
    """
    import pandas as pd
    
    import os
    if not os.path.exists(labels_csv):
        print(f"⚠️ Labels file not found: {labels_csv}")
        parent = os.path.dirname(labels_csv)
        fallbacks = [
            os.path.join(parent, "detailed_lables.csv"), # Common typo in user data
            os.path.join(parent, "labels.csv"),
            os.path.join(parent, "merged_labels.csv")
        ]
        for fb in fallbacks:
            if os.path.exists(fb):
                print(f"✅ Found fallback labels: {fb}")
                labels_csv = fb
                break
    
    labels_df = pd.read_csv(labels_csv)
    print(f"[H5Dataset] Loaded {len(labels_df)} labels from {labels_csv}")
    
    id_col = None
    for col in ['Participant_ID', 'participant_id', 'ID', 'id', 'PID', 'Participant']:
        if col in labels_df.columns:
            id_col = col
            break
    
    if id_col is None:
        raise ValueError(f"No ID column found in {labels_csv}")
    
    full_dataset = H5OmniFusionDataset(h5_dir, labels_csv=labels_csv)
    all_pids = full_dataset.participant_ids
    
    print(f"[H5Dataset] Found {len(all_pids)} H5 files, {len(labels_df)} labels")
    
    label_pids = set(labels_df[id_col].astype(str).tolist())
    
    valid_pids = []
    for p in all_pids:
        p_str = str(p)
        if p_str in label_pids:
            valid_pids.append(p)
        elif p_str.startswith('lmvd_') and p_str.split('_')[1] in label_pids:
            valid_pids.append(p)
        elif p_str.startswith('t_') and p_str.split('_')[1] in label_pids:
            valid_pids.append(p)
            
    print(f"[H5Dataset] {len(valid_pids)} PIDs have both H5 files and labels (fuzzy matched)")
    
    id_to_phq = {str(row[id_col]): row.get('PHQ8_Score', row.get('phq8_score', 0)) 
                 for _, row in labels_df.iterrows()}
    
    labels = []
    for pid in valid_pids:
        pid_str = str(pid)
        phq = 0
        if pid_str in id_to_phq:
            phq = id_to_phq[pid_str]
        elif pid_str.startswith('lmvd_') and pid_str.split('_')[1] in id_to_phq:
            phq = id_to_phq[pid_str.split('_')[1]]
        elif pid_str.startswith('t_') and pid_str.split('_')[1] in id_to_phq:
            phq = id_to_phq[pid_str.split('_')[1]]
        else:
            lbl = full_dataset._get_labels(pid)
            phq = lbl['phq_score'].item()
            
        labels.append(1 if phq >= 10 else 0)
    
    if StratifiedKFold is None:
        raise ImportError("scikit-learn required for K-Fold CV")
    
    np.random.seed(seed)
    skf = StratifiedKFold(n_splits=n_folds, shuffle=True, random_state=seed)
    
    for i, (train_idx, test_idx) in enumerate(skf.split(valid_pids, labels)):
        if i == fold_idx:
            train_pids = [valid_pids[j] for j in train_idx]
            test_pids = [valid_pids[j] for j in test_idx]
            break
    else:
        raise ValueError(f"Fold index {fold_idx} out of range for {n_folds} folds")
    
    train_labels = [labels[valid_pids.index(p)] for p in train_pids]
    
    from sklearn.model_selection import train_test_split
    
    if sum(train_labels) >= 10:
        actual_train_pids, val_pids = train_test_split(
            train_pids,
            test_size=0.1,  # 10% of training = ~150 samples
            stratify=train_labels,
            random_state=seed
        )
    else:
        val_size = len(train_pids) // 10
        val_pids = train_pids[-val_size:]
        actual_train_pids = train_pids[:-val_size]
        
    print(f"[H5Dataset] Fold {fold_idx}/{n_folds}: Train={len(actual_train_pids)}, Val={len(val_pids)}, Test={len(test_pids)}")
    
    train_dataset = H5OmniFusionDataset(h5_dir, participant_ids=actual_train_pids, labels_csv=labels_csv, max_seq_len=max_seq_len)
    val_dataset = H5OmniFusionDataset(h5_dir, participant_ids=val_pids, labels_csv=labels_csv, max_seq_len=max_seq_len)
    test_dataset = H5OmniFusionDataset(h5_dir, participant_ids=test_pids, labels_csv=labels_csv, max_seq_len=max_seq_len)
    
    train_dataset.set_training(True)
    val_dataset.set_training(False)
    test_dataset.set_training(False)
    
    print(f"[H5Dataset] Using natural class distribution (Focal Loss active)")
    train_dataset.participant_ids = train_pids
    
    train_loader = DataLoader(
        train_dataset,
        batch_size=batch_size,
        shuffle=True,
        num_workers=num_workers,
        collate_fn=h5_collate_fn,
        pin_memory=True,
    )
    
    val_loader = DataLoader(
        val_dataset,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        collate_fn=h5_collate_fn,
        pin_memory=True,
    )
    
    test_loader = DataLoader(
        test_dataset,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        collate_fn=h5_collate_fn,
        pin_memory=True,
    )
    
    return train_loader, val_loader, test_loader


