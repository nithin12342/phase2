    "sd = checkpoint.get('model_state_dict', checkpoint)\n",
    "sd = OrderedDict((k[7:] if k.startswith('module.') else k, v) for k, v in sd.items())\n",
    "\n",
    "config = H5Config.from_tier(ComputeTier.MEDIUM)\n",
    "model = H5OmniFusion(config)\n",
    "model.load_state_dict(sd, strict=False)\n",
    "model.to(DEVICE)\n",
    "model.eval()\n",
    "print('✅ Model Loaded')\n",
    "\n",
    "# Get Predictions\n",
    "all_labels, all_probs = [], []\n",
    "with torch.no_grad():\n",
    "    for batch in tqdm(test_loader, desc='Evaluating'):\n",
    "        input_keys = [k for k in batch.keys() if k not in ['label', 'labels', 'target', 'targets', 'participant_id']]\n",
    "        inputs = to_device({k: batch[k] for k in input_keys}, DEVICE)\n",
    "        labels = batch.get('label', batch.get('labels', {})).get('binary', torch.zeros(1)).to(DEVICE)\n",
    "        outputs = model(inputs)\n",
    "        all_probs.extend(outputs[0]['binary_prob'].cpu().numpy())\n",
    "        all_labels.extend(labels.cpu().numpy())\n",
    "\n",
    "y_true = np.array(all_labels)\n",
    "y_prob = np.array(all_probs)\n",
    "print(f'✅ Evaluated {len(y_true)} samples')\n",
    "\n",
    "# --- Threshold Optimization (Simulated Training) ---\n",
    "thresholds = np.arange(0.30, 0.85, 0.01)\n",
    "best_thr = 0.50\n",
    "best_j = -1.0\n",
    "metrics_log = []\n",
    "\n",
    "print('\\n🔍 Tuning Decision Threshold...')\n",
    "for thr in thresholds:\n",
    "    yp_t = (y_prob >= thr).astype(int)\n",
    "    tn, fp, fn, tp = confusion_matrix(y_true, yp_t).ravel()\n",
    "    sens = tp / (tp + fn) if (tp+fn)>0 else 0\n",
    "    spec = tn / (tn + fp) if (tn+fp)>0 else 0\n",
    "    f1 = f1_score(y_true, yp_t, zero_division=0)\n",
    "    \n",
    "    # Maximize Youden's J (Sens + Spec - 1)\n",
    "    j_stat = sens + spec - 1\n",
    "    metrics_log.append({'thr': thr, 'sens': sens, 'spec': spec, 'f1': f1, 'j': j_stat})\n",
    "    \n",
    "    if j_stat > best_j:\n",
    "        best_j = j_stat\n",
    "        best_thr = thr\n",
    "\n",
    "print(f'✅ Best Threshold: {best_thr:.2f} (Youden\\'s J = {best_j:.4f})')\n",
    "y_pred = (y_prob >= best_thr).astype(int)\n",
    "\n",
    "# --- Bootstrap Analysis ---\n",
    "n_boot = 1000\n",
    "boot_f1s = []\n",
    "np.random.seed(42)\n",
