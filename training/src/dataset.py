"""H5 Dataset loader for pre-processed OmniFusion features.

Loads embeddings and labels directly from H5 files generated by the
H5_OmniFusion_Colab_Runner pipeline.
"""

import torch
from torch.utils.data import Dataset, DataLoader
import numpy as np
import h5py
from pathlib import Path
from typing import Dict, List, Optional, Tuple, Union
import os
import glob

try:
    from sklearn.model_selection import StratifiedKFold, train_test_split
except ImportError:
    StratifiedKFold = None
    train_test_split = None


class H5OmniFusionDataset(Dataset):
    """
    Dataset for pre-extracted H5-OmniFusion features.
    
    Each H5 file contains:
    - {PID}/audio_embedding: (768,)
    - {PID}/text_embedding: (768,)
    - {PID}/video_embedding: (768,)
    - {PID}/face_embedding: (768,)
    - {PID}/tabular_embedding: (768,)
    - {PID}/phq8_score: (1,) or scalar
    """
    
    EMBEDDING_KEYS = [
        'audio_embedding',
        'text_embedding', 
        'video_embedding',
        'face_embedding',
        'tabular_embedding',
    ]
    
    def __init__(
        self,
        h5_dir: str,
        participant_ids: Optional[List[int]] = None,
        labels_csv: Optional[str] = None,
        depression_threshold: int = 10,
    ):
        """
        Initialize dataset.
        
        Args:
            h5_dir: Directory containing .h5 files (searches recursively)
            participant_ids: Optional list of PIDs to use (for train/val/test splits)
            labels_csv: Optional CSV with PHQ8 labels (overrides H5-embedded labels)
            depression_threshold: PHQ8 score >= this is considered depressed
        """
        self.h5_dir = Path(h5_dir)
        self.depression_threshold = depression_threshold
        self.labels_csv = labels_csv
        
        self._h5_paths = self._discover_h5_files()
        
        if participant_ids is not None:
             self.participant_ids = [p for p in participant_ids if p in self._h5_paths]
        else:
            self.participant_ids = sorted(list(self._h5_paths.keys()))
        
        self.external_labels = None
        if labels_csv and os.path.exists(labels_csv):
            self._load_external_labels(labels_csv)
        
        print(f"[H5Dataset] Loaded {len(self.participant_ids)} participants from {h5_dir}")
        self._print_label_distribution()
    
    def _discover_h5_files(self) -> Dict[int, Path]:
        """Discover available H5 files using recursive search."""
        h5_files = {}
        
        search_pattern = str(self.h5_dir / "**" / "*.h5")
        found_files = glob.glob(search_pattern, recursive=True)
        
        print(f"[H5Dataset] Found {len(found_files)} .h5 files in {self.h5_dir}")
        
        for file_path in found_files:
            path_obj = Path(file_path)
            try:
                if path_obj.stem.isdigit():
                    pid = int(path_obj.stem)
                    h5_files[pid] = path_obj
            except ValueError:
                continue
                
        return h5_files
    
    def _get_h5_path(self, pid: int) -> Optional[Path]:
        """Get the H5 file path for a participant ID."""
        return self._h5_paths.get(pid)
    
    def _load_external_labels(self, csv_path: str):
        """Load labels from external CSV file."""
        import pandas as pd
        try:
            df = pd.read_csv(csv_path)
            
            id_col = next((col for col in ['Participant_ID', 'participant_id', 'ID', 'id', 'PID'] if col in df.columns), None)
            phq_col = next((col for col in ['PHQ8_Score', 'phq8_score', 'PHQ_Score', 'phq_score'] if col in df.columns), None)
            
            if id_col and phq_col:
                self.external_labels = {int(row[id_col]): float(row[phq_col]) for _, row in df.iterrows()}
                print(f"[H5Dataset] Loaded {len(self.external_labels)} external labels from {csv_path}")
        except Exception as e:
            print(f"[H5Dataset] Warning: Failed to load external labels: {e}")
    
    def _print_label_distribution(self):
        """Print the distribution of depression labels."""
        pos_count = 0
        total = len(self.participant_ids)
        if total == 0:
            return
            
        for pid in self.participant_ids:
            labels = self._get_labels(pid)
            if labels['binary'].item() == 1:
                pos_count += 1
                
        neg_count = total - pos_count
        print(f"[H5Dataset] Distribution: {pos_count} Depressed ({100*pos_count/total:.1f}%), "
              f"{neg_count} Control ({100*neg_count/total:.1f}%)")
    
    def __len__(self) -> int:
        return len(self.participant_ids)
    
    def __getitem__(self, idx: int) -> Dict[str, torch.Tensor]:
        """Get a single sample."""
        pid = self.participant_ids[idx]
        h5_path = self._get_h5_path(pid)
        
        sample = {'participant_id': pid}
        
        try:
            with h5py.File(h5_path, 'r') as f:
                grp = f[str(pid)] if str(pid) in f else f
                
                for key in self.EMBEDDING_KEYS:
                    target_key = key.replace('_embedding', '_features')
                    if key in grp:
                        data = grp[key][()]
                        tensor_data = torch.from_numpy(data).float()
                        if tensor_data.dim() > 1:
                            tensor_data = tensor_data.mean(dim=0) # Simple aggregation if needed
                        sample[target_key] = tensor_data.view(-1) # Ensure 1D
                    else:
                        sample[target_key] = torch.zeros(768)
        except Exception as e:
            print(f"Error reading {h5_path}: {e}")
            for key in self.EMBEDDING_KEYS:
                 sample[key.replace('_embedding', '_features')] = torch.zeros(768)
        
        sample['targets'] = self._get_labels(pid)
        
        return sample
    
    def _get_labels(self, pid: int) -> Dict[str, torch.Tensor]:
        """Get labels for a participant."""
        phq_score = 0.0
        
        if self.external_labels and pid in self.external_labels:
            phq_score = self.external_labels[pid]
        else:
            h5_path = self._get_h5_path(pid)
            if h5_path:
                try:
                    with h5py.File(h5_path, 'r') as f:
                        grp = f[str(pid)] if str(pid) in f else f
                        if 'phq8_score' in grp:
                            score = grp['phq8_score'][()]
                            phq_score = float(score)
                except:
                    pass
        
        binary = 1 if phq_score >= self.depression_threshold else 0
        return {
            'binary': torch.tensor(binary, dtype=torch.long),
            'phq_score': torch.tensor(phq_score, dtype=torch.float),
        }


def h5_collate_fn(batch: List[Dict]) -> Dict[str, torch.Tensor]:
    """Custom collate function."""
    result = {}
    
    result['targets'] = {
        'binary': torch.stack([b['targets']['binary'] for b in batch]),
        'phq_score': torch.stack([b['targets']['phq_score'] for b in batch]),
    }
    
    result['participant_id'] = [b['participant_id'] for b in batch]
    
    feature_keys = [k for k in batch[0].keys() if k.endswith('_features')]
    for key in feature_keys:
        result[key] = torch.stack([b[key] for b in batch])
        
    return result


def create_dataloaders(
    h5_dir: str,
    batch_size: int = 8,
    n_folds: int = 5,
    fold_idx: int = 0,
    num_workers: int = 0,
    seed: int = 42,
    labels_csv: Optional[str] = None
) -> Tuple[DataLoader, DataLoader, Dict]:
    """Create stratified K-Fold dataloaders."""
    
    dataset = H5OmniFusionDataset(h5_dir, labels_csv=labels_csv)
    
    labels = [dataset._get_labels(pid)['binary'].item() for pid in dataset.participant_ids]
    
    if StratifiedKFold and len(labels) >= n_folds:
        skf = StratifiedKFold(n_splits=n_folds, shuffle=True, random_state=seed)
        splits = list(skf.split(dataset.participant_ids, labels))
        train_idx, val_idx = splits[fold_idx]
        
        train_pids = [dataset.participant_ids[i] for i in train_idx]
        val_pids = [dataset.participant_ids[i] for i in val_idx]
    else:
        print("Warning: Doing random split instead of StratifiedKFold")
        all_pids = dataset.participant_ids
        n_val = len(all_pids) // n_folds
        val_pids = all_pids[fold_idx*n_val : (fold_idx+1)*n_val]
        train_pids = [p for p in all_pids if p not in val_pids]
    
    train_dataset = H5OmniFusionDataset(h5_dir, participant_ids=train_pids, labels_csv=labels_csv)
    val_dataset = H5OmniFusionDataset(h5_dir, participant_ids=val_pids, labels_csv=labels_csv)
    
    train_loader = DataLoader(
        train_dataset,
        batch_size=batch_size,
        shuffle=True,
        num_workers=num_workers,
        collate_fn=h5_collate_fn,
        pin_memory=True
    )
    
    val_loader = DataLoader(
        val_dataset,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        collate_fn=h5_collate_fn,
        pin_memory=True
    )
    
    train_labels = [train_dataset._get_labels(p)['binary'].item() for p in train_dataset.participant_ids]
    val_labels = [val_dataset._get_labels(p)['binary'].item() for p in val_dataset.participant_ids]
    
    info = {
        'fold': fold_idx,
        'n_train': len(train_dataset),
        'n_val': len(val_dataset),
        'train_positive_ratio': sum(train_labels) / len(train_labels) if train_labels else 0,
        'val_positive_ratio': sum(val_labels) / len(val_labels) if val_labels else 0
    }
    
    return train_loader, val_loader, info
